export function personalArt(kind: TaskKind): HTMLCanvasElement {
  const canvas = document.createElement('canvas');
  canvas.width = 98;
  canvas.height = 114;
  canvas.setAttribute('aria-hidden','true');
  const ctx = canvas.getContext('2d')!;
  for (const [color, x, y, ...vertices] of facets[kind]) {
    ctx.beginPath();
    ctx.moveTo(x+1, y);
    for (let i=0; i<vertices.length; i+=2) ctx.lineTo(vertices[i]!+1, vertices[i+1]!);
    ctx.closePath();
    ctx.fillStyle = ctx.strokeStyle = color;
    ctx.lineWidth = .45;
    ctx.stroke();
    ctx.fill();
  }
  ctx.globalCompositeOperation = 'source-atop';
  for (let y=0; y<canvas.height; y+=2) {
    ctx.fillStyle = y%4===0 ? '#fff1cb14' : '#24122f15';
    for (let x=y%4; x<canvas.width; x+=4) ctx.fillRect(x,y,1,1);
  }
  return canvas;
}
